// Screenshot tour: visits every route, tab and form of the UI on the demo instance
// and saves full-page PNGs at 1440×900 plus INDEX.md. A failing step is recorded and the tour goes
// on; the run fails at the end listing the steps that did not make it.
import fs from 'node:fs';
import path from 'node:path';
import { expect, request, test, type Page } from '@playwright/test';

interface State {
  origin: string;
  present: number;
  users: Record<string, string>;
  docIds: Record<string, string>;
  /** `brain migrate-spaces --preview` of the demo pair, taken before the seed applied it. */
  migratePreview?: string;
}
function state(): State {
  const p = process.env.SHOTS_STATE;
  if (!p) throw new Error('SHOTS_STATE is not set');
  return JSON.parse(fs.readFileSync(p, 'utf8')) as State;
}

const OUT = process.env.SHOTS_OUT ?? path.resolve(import.meta.dirname, '..', '..', 'artifacts', 'screenshots');
interface Entry {
  file: string;
  route: string;
  description: string;
  as: string;
}
// The tour state lives on disk: a failed test restarts the worker, and numbering must go on.
const STATE_FILE = path.join(OUT, '.tour.json');
interface Tour {
  entries: Entry[];
  failures: string[];
}
function load(): Tour {
  return fs.existsSync(STATE_FILE) ? (JSON.parse(fs.readFileSync(STATE_FILE, 'utf8')) as Tour) : { entries: [], failures: [] };
}
function save(t: Tour): void {
  fs.writeFileSync(STATE_FILE, JSON.stringify(t));
  writeIndex(t);
}
let who = 'anonymous';

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/** Waits until the page settles: no requests in flight, no spinners, fonts loaded. */
async function settle(page: Page): Promise<void> {
  await page.waitForLoadState('networkidle');
  await expect(page.getByText('Loading…', { exact: true })).toHaveCount(0);
  await expect(page.getByText('Loading the editor…', { exact: true })).toHaveCount(0);
  await page.evaluate(() => document.fonts.ready.then(() => undefined));
  await page.waitForTimeout(150);
}

async function shot(page: Page, name: string, description: string): Promise<void> {
  await settle(page);
  const t = load();
  const n = String(t.entries.length + 1).padStart(2, '0');
  const file = `${n}-${slug(name)}.png`;
  // Mouse away from everything: no hover states in the picture.
  await page.mouse.move(0, 0);
  // The layout is one screen high (h-dvh) and <main> scrolls inside it, so Playwright's fullPage alone
  // would cut long pages at 900 px: grow the viewport by the largest inner overflow, then restore it.
  const extra = await page.evaluate(() => {
    let max = 0;
    for (const el of Array.from(document.querySelectorAll<HTMLElement>('body *'))) {
      const oy = getComputedStyle(el).overflowY;
      if ((oy === 'auto' || oy === 'scroll') && el.clientHeight > 0) max = Math.max(max, el.scrollHeight - el.clientHeight);
    }
    return max;
  });
  const base = page.viewportSize() ?? { width: 1440, height: 900 };
  if (extra > 0) {
    await page.setViewportSize({ width: base.width, height: Math.min(base.height + extra, 16_000) });
    await page.waitForTimeout(150);
  }
  await page.screenshot({ path: path.join(OUT, file), fullPage: true, animations: 'disabled', caret: 'hide' });
  if (extra > 0) await page.setViewportSize(base);
  const u = new URL(page.url());
  t.entries.push({ file, route: u.pathname + u.search, description, as: who });
  save(t);
}

/** One tour step: an error is recorded, the tour continues from a fresh navigation. */
async function step(name: string, fn: () => Promise<void>): Promise<void> {
  try {
    await test.step(name, fn);
  } catch (e) {
    const t = load();
    t.failures.push(`${who}: ${name}: ${(e as Error).message.split('\n')[0]}`);
    save(t);
  }
}

async function visit(page: Page, url: string, name: string, description: string): Promise<void> {
  await step(name, async () => {
    await page.goto(url);
    await shot(page, name, description);
  });
}

async function login(page: Page, name: string): Promise<void> {
  const s = state();
  await page.goto('/login');
  await page.getByLabel('Name').fill(name);
  await page.getByLabel('Password').fill(s.users[name] ?? '');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page.getByRole('button', { name: /^Account menu/ })).toBeVisible();
  who = name;
}

