function writeIndex({ entries, failures }: Tour): void {
  const lines = [
    '# Screenshot tour of the Brain web UI',
    '',
    'Generated by `npm run screenshots` (scripts/screenshots-server.ts + web/screenshots/tour.spec.ts) on a throwaway demo',
    'instance with a fixed clock (2026-11-17 10:00 UTC). Viewport 1440×900, full-page PNGs, light theme.',
    '',
    'Demo seed: superadmin `alice`; humans `bob` (manager of alice-project-agent) and `dave` (disabled); agents',
    'alice-assistant (admin), alice-helper, alice-coder, bob-agent, alice-project-agent, ext-bob-agent (external), old-scraper',
    '(disabled); spaces shared (executable), handoff (shown as General, messages on), admin, proj-alpha (Alpha, messages on; proj-alpha-inbox is an',
    'alias of it, made by `migrate-spaces`; its preview is in migrate-spaces-preview.txt), old-wiki (archived).',
    '',
    'Not in the UI (no screen to capture): webhooks (API only: admin_webhook_*); the admin “tokens” view is the Connection',
    'tab of each agent’s page; access rules are a space’s Members tab (Advanced access) and an agent’s Access tab.',
    '',
    '| # | File | Signed in as | Route | What it shows |',
    '| --- | --- | --- | --- | --- |',
    ...entries.map((e, i) => `| ${i + 1} | [${e.file}](${e.file}) | ${e.as} | \`${e.route}\` | ${e.description} |`),
    '',
  ];
  if (failures.length) lines.push('## Steps that failed', '', ...failures.map((f) => `- ${f}`), '');
  fs.writeFileSync(path.join(OUT, 'INDEX.md'), lines.join('\n'));
}

